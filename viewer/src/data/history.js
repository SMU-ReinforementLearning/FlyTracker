const dateLabel = (iso) => {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(iso)) return iso
  const [y, m, d] = iso.split('-').map(Number)
  return `${y}년 ${m}월 ${d}일`
}

/** issue 하나의 제목, PR 을 올린 사람, merge 날짜(ISO), 환경 버전, GitHub 주소. 표에 없으면 null. 계보 화면이 쓴다(lineage.js). */
export function issueOf(number) {
  const meta = ISSUES[number]
  return meta ? { number, ...meta, url: `${REPO}/issues/${number}` } : null
}

/**
 * src 의 값을 마지막으로 정한 issue. 환경 버전이 envVersion 인 실행에 들어 있는 변경 가운데 가장 늦은 것이다.
 * 돌려주는 것: { issue: { number, title, url, author, merged }, why }. 모르는 줄이면 null.
 */
export function changeOf(src, envVersion) {
  const entries = (HISTORY[src] ?? []).filter(([n]) => ISSUES[n] && ISSUES[n].env <= envVersion)
  if (entries.length === 0) return null
  const [number, why] = entries.at(-1)
  const { title, author, merged } = ISSUES[number]
  return { issue: { number, title, url: `${REPO}/issues/${number}`, author, merged: dateLabel(merged) }, why }
}